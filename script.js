// --- LÓGICA DO TEMA ESCURO / CLARO ---
function alternarTema() {
  const body = document.body;
  const icone = document.getElementById('icone-tema');

  body.classList.toggle('dark-theme');

  if (body.classList.contains('dark-theme')) {
    icone.innerText = '☀️'; // Mostra o sol quando estiver no modo escuro
    localStorage.setItem('tema', 'escuro');
  } else {
    icone.innerText = '🌙'; // Mostra a lua quando estiver no modo claro
    localStorage.setItem('tema', 'claro');
  }
}

// Carregar o tema salvo pelo usuário
function carregarTemaSalvo() {
  const temaSalvo = localStorage.getItem('tema');
  const icone = document.getElementById('icone-tema');

  if (temaSalvo === 'escuro') {
    document.body.classList.add('dark-theme');
    if (icone) icone.innerText = '☀️';
  }
}

// Executa ao carregar a página
carregarTemaSalvo();

// --- FUNÇÕES DOS CARDS E MODAL ---

function curtirPost(botao) {
  const contadorSpan = botao.querySelector('span');
  let curtidasAtuais = parseInt(contadorSpan.innerText);
  contadorSpan.innerText = curtidasAtuais + 1;
  
  botao.style.transform = "scale(1.2)";
  setTimeout(() => {
      botao.style.transform = "scale(1)";
  }, 150);
}

function filtrarDestinos(categoria, botaoClicado) {
  const cards = document.querySelectorAll('.card');
  const botoes = document.querySelectorAll('.btn-filtro');

  botoes.forEach(btn => btn.classList.remove('active'));
  botaoClicado.classList.add('active');

  cards.forEach(card => {
      const categoriaCard = card.getAttribute('data-categoria');
      if (categoria === 'todos' || categoriaCard === categoria) {
          card.style.display = "flex";
      } else {
          card.style.display = "none";
      }
  });
}

function abrirGuiaCompleto(paisKey) {
  const dados = dadosGuias[paisKey];
  if (!dados) return;

  const modal = document.getElementById('modal-guia');
  const modalBody = document.getElementById('modal-body');

  modalBody.innerHTML = `
    <img src="${dados.capa}" class="modal-header-img" alt="${dados.titulo}">
    <div class="modal-body-content">
      <h2>${dados.titulo}</h2>
      <p class="intro">${dados.descricao}</p>

      <h3 class="modal-secao-titulo">📸 Galeria do Destino</h3>
      <div class="grid-fotos">
        <img src="${dados.galeria[0]}" alt="Foto 1">
        <img src="${dados.galeria[1]}" alt="Foto 2">
      </div>

      <h3 class="modal-secao-titulo">💡 Dicas Essenciais de Viagem</h3>
      <ul class="lista-dicas">
        ${dados.dicas.map(dica => `<li>${dica}</li>`).join('')}
      </ul>
    </div>
  `;

  modal.classList.add('active');
}

function fecharModal() {
  const modal = document.getElementById('modal-guia');
  modal.classList.remove('active');
}

window.onclick = function(event) {
  const modal = document.getElementById('modal-guia');
  if (event.target === modal) {
    fecharModal();
  }
}